public class TowDimStaticArray {

    

public static void main(String args[]){
    int x[][]={{56,4,7},{3,56,1},{243,98,97}};
    for(int i=0;i<x.length;i++){
        for(int j=0;j<x.length;j++){
            System.out.print(x[i][j] +" ");
            
        }
        System.out.println();
    }
}
}
